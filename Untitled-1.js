// Khai báo biến tên và tuổi
let ten = "Nguyen Quang Huy";
let tuoi = 20;

// In lời chào và thông tin ra màn hình Terminal
console.log("Xin chào, mình là " + ten + ", năm nay mình " + tuoi + " tuổi.");

// Thử nghiệm phép tính và hiện tượng Vibe Coding ('10' + 20)
console.log("Kết quả của '10' + 20 là: " + ('10' + 20)); 
// Giải thích: Trả về chuỗi "1020" do cơ chế nối chuỗi của JavaScript

// Cách khắc phục để ra kết quả phép toán cộng số học (30)
console.log("Kết quả sau khi ép kiểu Number('10') + 20 là: " + (Number('10') + 20));

// Thử nghiệm các phép toán trừ, nhân, chia cơ bản khác
let a = 15;
let b = 5;
console.log("Phép trừ (a - b):", a - b); // Kết quả: 10
console.log("Phép nhân (a * b):", a * b); // Kết quả: 75
console.log("Phép chia (a / b):", a / b); // Kết quả: 3